-- Run this script in the Supabase SQL Editor for the Pedalya booking flow.
-- The app connects to Supabase PostgreSQL through Laravel; do not put a
-- Supabase service-role key or PayMongo secret in frontend JavaScript.

ALTER TABLE public.users
    ALTER COLUMN mobile_number TYPE text USING mobile_number::text;

CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique
    ON public.users (email);

CREATE TABLE IF NOT EXISTS public.services (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug text NOT NULL UNIQUE,
    name text NOT NULL,
    description text NOT NULL DEFAULT '',
    duration_minutes integer NOT NULL CHECK (duration_minutes > 0),
    price numeric(10, 2) NOT NULL CHECK (price >= 0),
    capacity_per_slot integer NOT NULL DEFAULT 2 CHECK (capacity_per_slot > 0),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public.bookings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference text NOT NULL UNIQUE,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    service_id bigint NOT NULL REFERENCES public.services(id) ON DELETE RESTRICT,
    customer_name text NOT NULL,
    customer_email text NOT NULL,
    customer_mobile_number text NOT NULL,
    appointment_at timestamptz NOT NULL,
    duration_minutes integer NOT NULL CHECK (duration_minutes > 0),
    service_price numeric(10, 2) NOT NULL CHECK (service_price >= 0),
    bike_notes text,
    consent_confirmed boolean NOT NULL DEFAULT false,
    booking_status text NOT NULL DEFAULT 'pending'
        CHECK (booking_status IN ('pending', 'confirmed', 'rejected', 'cancelled', 'completed')),
    payment_status text NOT NULL DEFAULT 'pending'
        CHECK (payment_status IN ('pending', 'paid', 'failed')),
    calendar_status text NOT NULL DEFAULT 'not_applicable'
        CHECK (calendar_status IN ('not_applicable', 'pending', 'synchronized', 'failed')),
    calendar_event_id text,
    calendar_sync_attempts smallint NOT NULL DEFAULT 0 CHECK (calendar_sync_attempts >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS bookings_user_appointment_idx
    ON public.bookings (user_id, appointment_at DESC);
CREATE INDEX IF NOT EXISTS bookings_appointment_status_idx
    ON public.bookings (appointment_at, booking_status);

CREATE TABLE IF NOT EXISTS public.payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL UNIQUE REFERENCES public.bookings(id) ON DELETE CASCADE,
    provider text NOT NULL DEFAULT 'paymongo',
    provider_checkout_session_id text UNIQUE,
    provider_payment_intent_id text,
    provider_payment_id text,
    checkout_url text,
    amount_minor bigint NOT NULL CHECK (amount_minor > 0),
    currency text NOT NULL DEFAULT 'PHP' CHECK (currency = 'PHP'),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'failed')),
    webhook_event_id text UNIQUE,
    paid_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

